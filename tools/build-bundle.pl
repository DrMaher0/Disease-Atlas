#!/usr/bin/perl
use strict;
use warnings;
use File::Basename qw(dirname);
use IO::Compress::Gzip qw(gzip $GzipError);
use MIME::Base64 qw(encode_base64);

my $root = dirname(dirname(__FILE__));
my $out  = "$root/Disease-Atlas-Single-File.html";

sub slurp {
  my ($path) = @_;
  open my $fh, '<:raw', $path or die "Cannot read $path: $!";
  local $/;
  my $text = <$fh>;
  close $fh;
  return $text;
}

my $html = slurp("$root/index.html");

# Inline the stylesheet uncompressed so the boot screen is styled immediately.
my $css = slurp("$root/styles.css");
$css =~ s{</style}{<\\/style}gi;
$html =~ s{<link rel="stylesheet" href="styles\.css">}{<style>\n$css\n</style>};

# Collect the boot scripts in document order (tests excluded). Each source is
# joined with a NUL separator, which cannot occur inside the text files.
my @srcs = $html =~ m{<script defer src="([^"]+)"></script>}g;
my $count = 0;
my $payload = '';
for my $src (@srcs) {
  next if $src =~ m{^tests/};
  $payload .= slurp("$root/$src") . "\x00";
  $count++;
}
# The lazy-loaded diagrams travel as the final segment. The bootstrap stores
# them in #da-diagrams-data so app.js loadDiagrams() works exactly as before.
$payload .= slurp("$root/js/data/30-body-diagrams.js");

my $gz;
gzip(\$payload => \$gz, -Level => 9) or die "gzip failed: $GzipError";
my $b64 = encode_base64($gz, '');

# Everything now lives in the compressed payload; drop the external script tags.
$html =~ s{<script defer src="[^"]+"></script>\s*}{}g;

$html =~ s{<title>Disease Atlas</title>}{<title>Disease Atlas (single file)</title>};
$html =~ s{(<head>)}{$1\n<!-- Generated by tools/build-bundle.pl. Edit the modular files, then rebuild. -->};

# Tiny uncompressed loader. DecompressionStream ships in every browser that can
# render this app's color-mix() CSS (2023+), so the core experience is preserved.
my $bootstrap = <<'BOOT';
(function(){
  function fail(msg){var b=document.querySelector('.boot-card');if(b){b.textContent='';var p=document.createElement('p');p.className='boot-title';p.textContent=msg;b.appendChild(p);}}
  if(!('DecompressionStream' in window)){fail('This compressed edition needs a recent browser (2023 or newer). Please open the modular index.html instead.');return;}
  try{
    var b64=document.getElementById('da-payload').textContent.replace(/\s+/g,'');
    var bin=atob(b64),bytes=new Uint8Array(bin.length);
    for(var i=0;i<bin.length;i++)bytes[i]=bin.charCodeAt(i);
    var stream=new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
    new Response(stream).text().then(function(text){
      var parts=text.split('\x00');
      var diagrams=parts.pop();
      var dd=document.getElementById('da-diagrams-data');if(dd)dd.textContent=diagrams;
      for(var j=0;j<parts.length;j++){var s=document.createElement('script');s.textContent=parts[j];document.body.appendChild(s);}
    }).catch(function(e){fail('Could not start Disease Atlas. '+((e&&e.message)||''));});
  }catch(e){fail('Could not start Disease Atlas. '+((e&&e.message)||''));}
})();
BOOT

my $inject = qq{<script type="text/plain" id="da-diagrams-data"></script>\n}
           . qq{<script type="text/plain" id="da-payload">$b64</script>\n}
           . qq{<script>\n$bootstrap</script>\n};
$html =~ s{</body>}{$inject</body>};

open my $ofh, '>:raw', $out or die "Cannot write $out: $!";
print $ofh $html;
close $ofh;

my $size = -s $out;
printf "Wrote %s\nCompressed %d boot scripts + diagrams (gzip+base64).\nSize: %.2f MB\n", $out, $count, $size / 1048576;