#!/usr/bin/perl
use strict;
use warnings;
use File::Basename qw(dirname);

my $root = dirname(dirname(__FILE__));
my $out  = "$root/Disease-Atlas-Single-File.html";

sub slurp {
  my ($path) = @_;
  open my $fh, '<:raw', $path or die "Cannot read $path: $!";
  local $/;
  my $text = <$fh>;
  close $fh;
  return $text;
}

my $html = slurp("$root/index.html");

my $css = slurp("$root/styles.css");
$css =~ s{</style}{<\\/style}gi;
$html =~ s{<link rel="stylesheet" href="styles\.css">}{<style>\n$css\n</style>};

my $count = 0;
$html =~ s{<script defer src="([^"]+)"></script>}{
  my $src = $1;
  if ($src =~ m{^tests/}) { '' }
  else {
    my $code = slurp("$root/$src");
    $code =~ s{</script}{<\\/script}gi;
    $count++;
    "<script>\n$code\n</script>"
  }
}ge;

$html =~ s{<title>Disease Atlas</title>}{<title>Disease Atlas (single file)</title>};
$html =~ s{(<head>)}{$1\n<!-- Generated by tools/build-bundle.pl. Edit the modular files, then rebuild. -->};

open my $ofh, '>:raw', $out or die "Cannot write $out: $!";
print $ofh $html;
close $ofh;

my $size = -s $out;
printf "Wrote %s\nInlined %d scripts and the stylesheet.\nSize: %.2f MB\n", $out, $count, $size / 1048576;
