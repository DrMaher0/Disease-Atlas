# tools/build-bundle.ps1
# Pure PowerShell bundler for Disease Atlas Single-File distribution
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$out  = Join-Path $root "Disease-Atlas-Single-File.html"

Write-Host "Reading index.html and styles.css..."
$html = [System.IO.File]::ReadAllText((Join-Path $root "index.html"), [System.Text.Encoding]::UTF8)
$css  = [System.IO.File]::ReadAllText((Join-Path $root "styles.css"), [System.Text.Encoding]::UTF8)

# Escape closing style tags in CSS
$css = [System.Text.RegularExpressions.Regex]::Replace($css, "</style", "<\`/style", [System.Text.RegularExpressions.RegexOptions]::IgnoreCase)
$html = $html.Replace('<link rel="stylesheet" href="styles.css">', "<style>`n$css`n</style>")

# Find scripts
$matches = [System.Text.RegularExpressions.Regex]::Matches($html, '<script defer src="([^"]+)"></script>')
$payloadParts = [System.Collections.Generic.List[string]]::new()
$count = 0

foreach ($m in $matches) {
    $src = $m.Groups[1].Value
    if ($src -like "tests/*") { continue }
    $scriptPath = Join-Path $root $src
    $scriptText = [System.IO.File]::ReadAllText($scriptPath, [System.Text.Encoding]::UTF8)
    $payloadParts.Add($scriptText)
    $count++
}

# Final segment: lazy diagrams
$diagramPath = Join-Path $root "js/data/30-body-diagrams.js"
$diagramText = [System.IO.File]::ReadAllText($diagramPath, [System.Text.Encoding]::UTF8)
$payloadParts.Add($diagramText)

# Join with NUL character
$payloadString = [string]::Join([char]0, $payloadParts)
$payloadBytes  = [System.Text.Encoding]::UTF8.GetBytes($payloadString)

Write-Host "Compressing $($count) scripts + diagrams with Gzip (CompressionLevel: Optimal)..."
$ms = [System.IO.MemoryStream]::new()
$gz = [System.IO.Compression.GZipStream]::new($ms, [System.IO.Compression.CompressionLevel]::Optimal)
$gz.Write($payloadBytes, 0, $payloadBytes.Length)
$gz.Close()
$compressedBytes = $ms.ToArray()
$b64 = [Convert]::ToBase64String($compressedBytes)

# Remove script tags
$html = [System.Text.RegularExpressions.Regex]::Replace($html, '<script defer src="[^"]+"></script>\s*', '')

# Title & Head marker
$html = $html.Replace('<title>Disease Atlas</title>', '<title>Disease Atlas (single file)</title>')
$html = $html.Replace('<head>', "<head>`n<!-- Generated by tools/build-bundle.ps1. Edit modular files, then rebuild. -->")

$bootstrap = @'
(function(){
  function fail(msg){var b=document.querySelector('.boot-card');if(b){b.textContent='';var p=document.createElement('p');p.className='boot-title';p.textContent=msg;b.appendChild(p);}}
  if(!('DecompressionStream' in window)){fail('This compressed edition needs a recent browser (2023 or newer). Please open the modular index.html instead.');return;}
  try{
    var b64=document.getElementById('da-payload').textContent.replace(/\s+/g,'');
    var bin=atob(b64),bytes=new Uint8Array(bin.length);
    for(var i=0;i<bin.length;i++)bytes[i]=bin.charCodeAt(i);
    var stream=new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
    new Response(stream).text().then(function(text){
      var parts=text.split('\x00');
      var diagrams=parts.pop();
      var dd=document.getElementById('da-diagrams-data');if(dd)dd.textContent=diagrams;
      for(var j=0;j<parts.length;j++){var s=document.createElement('script');s.textContent=parts[j];document.body.appendChild(s);}
    }).catch(function(e){fail('Could not start Disease Atlas. '+((e&&e.message)||''));});
  }catch(e){fail('Could not start Disease Atlas. '+((e&&e.message)||''));}
})();
'@

$inject = "<script type=""text/plain"" id=""da-diagrams-data""></script>`n" +
          "<script type=""text/plain"" id=""da-payload"">$b64</script>`n" +
          "<script>`n$bootstrap</script>`n"

$html = $html.Replace('</body>', "$inject</body>")

[System.IO.File]::WriteAllText($out, $html, [System.Text.Encoding]::UTF8)

$fi = Get-Item $out
Write-Host ("Wrote {0}`nCompressed {1} boot scripts + diagrams.`nSize: {2:N2} MB" -f $out, $count, ($fi.Length / 1MB))
